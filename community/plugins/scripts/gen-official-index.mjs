// Generator: emit packages/manager/src/host/official-package-index.ts from the
// checked-in OFFICIAL_PACKAGE_REGISTRY plus the local deepseek-harness tree.
// Functional group is the harness packages/<group>/ directory; description is
// the package.json "description". A small manual override map covers legacy
// registry names that no longer exist under that exact name in the tree.
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const clone = dirname(fileURLToPath(import.meta.url))
const harness = process.argv[2] ?? 'E:\\KW\\qtGit\\deepseek-harness'
const packagesRoot = join(harness, 'packages')

const registryPath = join(clone, '..', 'packages', 'manager', 'src', 'host', 'official-package-registry.ts')
const registrySource = readFileSync(registryPath, 'utf8')
const registry = [...registrySource.matchAll(/'([^']+)'/g)].map(m => m[1]).filter(s => s.startsWith('@deepseek-ai/') || s.startsWith('cordis:'))

// Legacy registry names whose tree location or package name has moved since the
// registry snapshot. Group and description are hand-reviewed against the tree.
const overrides = {
  '@deepseek-ai/cordis-plugin-hmr': { group: 'cordis', description: 'Hot Module Replacement Plugin for Cordis' },
  '@deepseek-ai/cordis-plugin-loader': { group: 'cordis', description: 'Plugin loader for cordis' },
  '@deepseek-ai/cordis-plugin-timer': { group: 'cordis', description: 'Timer service for cordis' },
  '@deepseek-ai/dsh-agent-spine-demo': { group: 'core', description: 'Agent spine demonstration plugin' },
  '@deepseek-ai/dsh-client-runtime': { group: 'client', description: 'DeepSeek Harness browser client runtime' },
  '@deepseek-ai/dsh-client-schema-form': { group: 'client', description: 'JSON-schema-driven form renderer for the Web client' },
  '@deepseek-ai/dsh-client-web-react': { group: 'client', description: 'React bindings for the DeepSeek Harness Web client' },
  '@deepseek-ai/dsh-code-runtime-python': { group: 'code-runtime', description: 'CPython subprocess implementation of the DeepSeek Harness code-execution seam' },
  '@deepseek-ai/dsh-host-apiproxy': { group: 'api', description: 'DeepSeek Harness host API proxy' },
  '@deepseek-ai/dsh-session-persistence-sqlite': { group: 'session', description: 'SQLite session persistence' },
  '@deepseek-ai/dsh-tool-subagent-report': { group: 'subagent', description: 'Subagent report tool' },
  '@deepseek-ai/dsh-web-frontend': { group: 'web', description: 'Web application entry: vite build over the @deepseek-ai/dsh-client-web shell library' },
  'cordis:empty': { group: 'cordis', description: 'Cordis empty plugin builtin' },
  'cordis:include': { group: 'cordis', description: 'Cordis include builtin' },
}

const byName = new Map()
function walk(group) {
  const dir = join(packagesRoot, group)
  if (!existsSync(dir)) return
  for (const pkg of readdirSync(dir, { withFileTypes: true })) {
    if (!pkg.isDirectory()) continue
    const manifestPath = join(dir, pkg.name, 'package.json')
    if (!existsSync(manifestPath)) continue
    try {
      const m = JSON.parse(readFileSync(manifestPath, 'utf8'))
      if (typeof m.name === 'string') byName.set(m.name, { group, description: typeof m.description === 'string' ? m.description : null })
    } catch {}
  }
}
for (const group of readdirSync(packagesRoot, { withFileTypes: true })) {
  if (group.isDirectory()) walk(group.name)
}

const entries = []
let nullDescriptions = 0
for (const name of registry) {
  const found = overrides[name] ?? byName.get(name)
  if (found === undefined) throw new Error(`no source for registry entry ${name}`)
  if (found.description === null || found.description === '') nullDescriptions += 1
  entries.push({ name, group: found.group, description: found.description ?? null })
}
entries.sort((a, b) => a.name.localeCompare(b.name))

const lines = entries.map(e => `  ${JSON.stringify(e.name)}: { group: ${JSON.stringify(e.group)}, description: ${JSON.stringify(e.description)} },`)
const source = `/**
 * Checked-in functional index for the official DeepSeek Harness package set.
 * Generated by scripts/gen-official-index.mjs from the reviewed deepseek-ai/
 * deepseek-harness source tree; each module root maps to its harness
 * packages/<group>/ directory and package.json description. Legacy registry
 * names carry a hand-reviewed group and a conservative description.
 *
 * Regenerate after reviewing a new official Harness release, then run
 * pnpm --filter dsh-plugin-manager test to confirm key parity with
 * OFFICIAL_PACKAGE_REGISTRY.
 */
export interface OfficialPackageMeta {
  /** Harness functional group, or 'cordis' for Cordis builtins. */
  readonly group: string
  /** package.json description, or null when the package declares none. */
  readonly description: string | null
}

export const OFFICIAL_PACKAGE_INDEX: Readonly<Record<string, OfficialPackageMeta>> = Object.freeze({
${lines.join('\n')}
})

/** Functional group for one official module root, or undefined. */
export function officialGroup(packageName: string): string | undefined {
  return OFFICIAL_PACKAGE_INDEX[packageName]?.group
}

/** package.json description for one official module root, or undefined. */
export function officialDescription(packageName: string): string | null | undefined {
  return OFFICIAL_PACKAGE_INDEX[packageName]?.description
}
`

writeFileSync(join(clone, '..', 'packages', 'manager', 'src', 'host', 'official-package-index.ts'), source, 'utf8')
console.log(`wrote ${entries.length} entries; ${nullDescriptions} with null description`)
